public class Main {
    public static void main(String[] args) {
        char ch = 'A'; // 문자형 변수 ch에 문자열 'A' 할당
        int num = ch + 2; // 정수형 변수 num에 A=65 + 2 = 67 할당
        double result = num / 2.0; // 실수형 변수 result에 67 / 2.0 = 33.5 할당

        System.out.println(num);
        System.out.println(result);
    }
}

/* 정답
   67
   33.5 
*/